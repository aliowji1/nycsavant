/* Method: definitions, data sources, limits. */
S.pages = S.pages || {};

S.pages.about = async (root) => {
  const meta = await S.load("meta.json");
  const [e, l] = meta.definitions.on_sched.bus;
  root.innerHTML = `<div class="method">
  <div class="kicker">Method</div>
  <h1>How the numbers are made</h1>
  <p class="lede">Every night the site is rebuilt from a full day of MTA realtime feeds, saved every 30 seconds.
  Window: ${meta.dates.length} service days, ${S.fmt.date(meta.dates[0])} to ${S.fmt.date(meta.dates[meta.dates.length - 1])}. Last built ${meta.generated.replace("T", " ")}.</p>
  ${meta.simulated ? `<p class="card" style="border-color:#fab219"><b>This build uses simulated data.</b> The schedule, stations, routes and track shapes are the MTA's real
  static timetable, but what the trains and buses did was generated by a simulator so the pipeline could be tested end to end.
  Fleet numbers, delays, incidents and ridership here are invented. Don't draw conclusions about real lines from this build.</p>` : ""}

  <h2>Where the data comes from</h2>
  <ul>
    <li><b>Subway positions and arrivals:</b> the MTA's eight GTFS-realtime subway feeds. They publish predicted arrival times, not a log of what happened.
    For each train and stop we keep the last prediction seen before the stop drops off the train's list. Once a train is at the platform the feed reports its
    real arrival time, so the last value is close to the truth. Stops that vanish while still minutes away (re-routes, skipped stops) are thrown out.</li>
    <li><b>Buses:</b> MTA BusTime's GTFS-realtime vehicle positions, which include each bus's fleet number and its next stop.
    A stop's passage time is when the bus was seen stopped there, or the midpoint between the last snapshot before it and the first one after.</li>
    <li><b>Schedules, stations and track shapes:</b> the MTA's static GTFS, refreshed weekly.</li>
    <li><b>Ridership:</b> NY Open Data's hourly subway ridership by station complex (OMNY and MetroCard entries). Exits are estimated from the MTA's
    origin-destination dataset, which models where riders go from their tap patterns. It's an estimate, so we only use its shape.</li>
  </ul>

  <h2>Definitions</h2>
  <ul>
    <li><b>Complete trip:</b> seen at its first and last stop, and at 80% or more of its scheduled stops.</li>
    <li><b>On schedule:</b> subway trips arrive at the terminal no more than 5 minutes late (the MTA's terminal on-time standard; early is fine).
    Bus trips arrive between ${e / 60} minute early and ${l / 60} minutes late (the MTA's bus on-time standard).</li>
    <li><b>Time saved per trip:</b> the typical runtime for the same route, direction, pattern, day type and starting hour, minus this trip's runtime.
    Positive means faster than usual.</li>
    <li><b>Replacement level:</b> the on-schedule rate of the 20th-percentile vehicle (or scheduled trip) on the same line, among those with enough trips to rank.
    Rates are first shrunk toward the line average as if each vehicle had 10 extra average trips, so a handful of lucky or unlucky runs can't set the bar.</li>
    <li><b>TAR, trips above replacement:</b> on-schedule trips minus the trips a replacement-level vehicle would have delivered with the same workload.
    A bus with 60 trips, 48 on schedule, on a route whose replacement rate is 60% has 48 − 36 = <b>12 TAR</b>.</li>
    <li><b>Rank:</b> by TAR, within the line the vehicle ran most. Buses need ${meta.definitions.min_trips}+ complete trips; scheduled subway trips need 5 runs.</li>
    <li><b>Train speed vs. normal:</b> actual time between consecutive stations divided by the median for that segment and hour, minus one.</li>
  </ul>

  <h2>What this can't tell you</h2>
  <ul>
    <li><b>Individual subway cars.</b> NYC's public feeds don't say which cars make up a train, so there's no per-car ranking. The internal train ID changes
    whenever a train is re-routed, so it can't stand in for a car number either.</li>
    <li><b>Cause.</b> A bus that ranks low may have drawn the worst runs on a congested route. TAR compares buses on the same route to limit this, but luck
    and assignment still matter. Treat a ranking as a stat line, not a verdict on a bus or its operator.</li>
    <li><b>Precision.</b> Arrival times are good to within about half a polling interval (15 seconds). Feed outages leave gaps.</li>
  </ul>
  <h2>Credits</h2>
  <p>Inspired by <a href="https://mbtaviz.github.io">Visualizing MBTA Data</a> by Mike Barry and Brian Card, and by MBTA Savant.
  Built with D3. Data © MTA, used under the MTA's developer license terms.</p>
  </div>`;
};
